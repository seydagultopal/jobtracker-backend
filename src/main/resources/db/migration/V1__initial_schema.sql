-- Initial schema for new installations.
-- Existing non-empty databases are baselined at version 1; see Flyway settings.

CREATE TABLE users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email VARCHAR(255) NOT NULL UNIQUE,
    password VARCHAR(255) NOT NULL,
    first_name VARCHAR(255),
    last_name VARCHAR(255),
    phone VARCHAR(255),
    location VARCHAR(255),
    title VARCHAR(255),
    linkedin VARCHAR(255),
    github VARCHAR(255),
    bio TEXT,
    photo TEXT,
    cover_photo TEXT,
    experiences TEXT,
    educations TEXT,
    created_at TIMESTAMP WITHOUT TIME ZONE NOT NULL
);

CREATE TABLE job_applications (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    company_name VARCHAR(255) NOT NULL,
    position VARCHAR(255) NOT NULL,
    application_type VARCHAR(255),
    work_mode VARCHAR(255),
    location VARCHAR(255),
    salary VARCHAR(255),
    description TEXT,
    application_questions TEXT,
    platform VARCHAR(255),
    application_date DATE NOT NULL,
    status VARCHAR(255) NOT NULL,
    notes TEXT,
    user_id BIGINT NOT NULL REFERENCES users(id)
);

CREATE TABLE agendas (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    date DATE NOT NULL,
    notes TEXT,
    mood VARCHAR(255),
    user_id BIGINT NOT NULL REFERENCES users(id)
);

CREATE TABLE todo_items (
    db_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id BIGINT,
    text VARCHAR(255),
    completed BOOLEAN NOT NULL DEFAULT FALSE,
    agenda_id BIGINT REFERENCES agendas(id)
);

CREATE TABLE password_reset_token (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    token VARCHAR(255) NOT NULL UNIQUE,
    user_id BIGINT NOT NULL UNIQUE REFERENCES users(id),
    expiry_date TIMESTAMP WITHOUT TIME ZONE NOT NULL
);

CREATE TABLE courses (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title VARCHAR(255) NOT NULL,
    platform VARCHAR(255),
    progress INTEGER,
    status VARCHAR(255),
    user_id BIGINT NOT NULL REFERENCES users(id)
);

CREATE TABLE projects (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title VARCHAR(255) NOT NULL,
    tech VARCHAR(255),
    status VARCHAR(255),
    user_id BIGINT NOT NULL REFERENCES users(id)
);

CREATE TABLE skills (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(255) NOT NULL,
    level INTEGER,
    user_id BIGINT NOT NULL REFERENCES users(id)
);

CREATE INDEX idx_job_applications_user_id ON job_applications(user_id);
CREATE INDEX idx_agendas_user_id ON agendas(user_id);
CREATE INDEX idx_courses_user_id ON courses(user_id);
CREATE INDEX idx_projects_user_id ON projects(user_id);
CREATE INDEX idx_skills_user_id ON skills(user_id);
